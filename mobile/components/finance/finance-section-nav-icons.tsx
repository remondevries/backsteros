/**
 * Section icons for the iPad Finance left nav — parity with desktop
 * `FinanceSectionNavIcon`.
 */
export function FinanceSectionNavIcon({
  id,
  color,
  size = 16,
}: {
  id: MobileFinanceSectionId;
  color: string;
  size?: number;
}) {
  const props = { color, size } as const;
  switch (id) {
    case "dashboard":
      return <DashboardIcon {...props} />;
    case "transactions":
      return <TransactionsIcon {...props} />;
    case "invoices":
      return <InvoicesIcon {...props} />;
    case "goals":
      return <GoalsIcon {...props} />;
    case "cashflow":
      return <CashflowIcon {...props} />;
    case "accounts":
      return <AccountsIcon {...props} />;
    case "investments":
      return <InvestmentsIcon {...props} />;
    case "categories":
      return <CategoriesIcon {...props} />;
    case "recurrings":
      return <RecurringsIcon {...props} />;
  }
}
