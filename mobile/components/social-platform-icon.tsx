function resolvePlatform(platform: string): ContactSocialPlatform | "Other" {
  const trimmed = platform.trim();
  if (isContactSocialPlatform(trimmed)) return trimmed;
  const key = trimmed.toLowerCase();
  if (key === "linkedin" || key === "linked-in") return "LinkedIn";
  if (key === "instagram" || key === "ig") return "Instagram";
  if (key === "facebook" || key === "fb") return "Facebook";
  if (key === "x" || key === "twitter" || key === "x.com") return "X";
  if (key === "github" || key === "gh") return "GitHub";
  if (key === "discord") return "Discord";
  if (key === "slack") return "Slack";
  if (key === "website" || key === "web" || key === "site") return "Website";
  return "Other";
}

