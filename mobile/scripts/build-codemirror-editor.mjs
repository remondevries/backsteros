import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const entry = path.join(root, "codemirror-editor/src/main.ts");
const outDir = path.join(root, "lib/generated");
const outFile = path.join(outDir, "codemirror-editor-html.ts");

mkdirSync(outDir, { recursive: true });

const result = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: ["es2020"],
  minify: true,
  legalComments: "none",
});

const js = result.outputFiles?.[0]?.text;
if (!js) {
  throw new Error("esbuild produced no output");
}

const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no" />
  <style>
    html, body {
      margin: 0;
      padding: 0;
      width: 100%;
      height: 100%;
      background: #000000;
      color: #ededed;
      overflow: hidden;
    }
    #editor {
      width: 100%;
      height: 100%;
    }
    .cm-editor {
      height: 100%;
    }
  </style>
</head>
<body>
  <div id="editor"></div>
  <script>
${js}
  </script>
</body>
</html>`;

const moduleSource = `/* Generated by scripts/build-codemirror-editor.mjs — do not edit by hand. */
export const CODEMIRROR_EDITOR_HTML = ${JSON.stringify(html)};
`;

writeFileSync(outFile, moduleSource, "utf8");
console.log(`Wrote ${path.relative(root, outFile)} (${Math.round(html.length / 1024)} KB HTML)`);
