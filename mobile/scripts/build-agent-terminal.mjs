import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const entry = path.join(root, "agent-terminal/src/main.ts");
const outDir = path.join(root, "lib/generated");
const outFile = path.join(outDir, "agent-terminal-html.ts");

mkdirSync(outDir, { recursive: true });

const result = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: ["es2020"],
  minify: true,
  legalComments: "none",
});

const js = result.outputFiles?.[0]?.text;
if (!js) {
  throw new Error("esbuild produced no output");
}

const xtermCssPath = path.join(
  root,
  "node_modules/@xterm/xterm/css/xterm.css",
);
let xtermCss = "";
try {
  xtermCss = readFileSync(xtermCssPath, "utf8");
} catch {
  // pnpm may hoist
  const alt = path.join(
    root,
    "../node_modules/@xterm/xterm/css/xterm.css",
  );
  xtermCss = readFileSync(alt, "utf8");
}

const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no" />
  <style>
${xtermCss}
    html, body {
      margin: 0;
      padding: 0;
      width: 100%;
      height: 100%;
      background: #0f1115;
      color: #e8e8e8;
      overflow: hidden;
    }
    #terminal {
      width: 100%;
      height: 100%;
      padding: 4px;
      box-sizing: border-box;
    }
    .xterm, .xterm-viewport, .xterm-screen {
      height: 100%;
    }
  </style>
</head>
<body>
  <div id="terminal"></div>
  <script>
${js}
  </script>
</body>
</html>`;

const moduleSource = `/* Generated by scripts/build-agent-terminal.mjs — do not edit by hand. */
export const AGENT_TERMINAL_HTML = ${JSON.stringify(html)};
`;

writeFileSync(outFile, moduleSource, "utf8");
console.log(
  `Wrote ${path.relative(root, outFile)} (${Math.round(html.length / 1024)} KB HTML)`,
);
